from __future__ import annotations

import json

from mission_engine import (
    MissionOutcome,
    build_prompt,
    generate_mission,
    load_fallbacks,
    parse_mission,
)
from models import MAX_STEPS_BY_DURATION, MissionRequest
from providers import StaticProvider
from providers.base import (
    GenerationResult,
    InferenceProvider,
    ProviderAuthError,
)
from safety import check_mission


def make_request(**overrides) -> MissionRequest:
    payload = {
        "duration_minutes": 20,
        "environment": "park",
        "difficulty": "easy",
        "interests": ["birds"],
    }
    payload.update(overrides)
    return MissionRequest(**payload)


def test_valid_ai_generation(settings, valid_mission_payload):
    provider = StaticProvider([json.dumps(valid_mission_payload)])
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert outcome.mission.source == "ai"
    assert outcome.mission.provider == "static"
    assert outcome.mission.model == "static-fixture"
    assert outcome.error is None
    assert outcome.attempts == 1
    assert len(outcome.mission.steps) == 3
    assert outcome.mission.duration_minutes == 20
    assert outcome.mission.environment == "park"


def test_malformed_json_falls_back(settings):
    provider = StaticProvider(["this is not json at all"])
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert outcome.mission.source == "curated_fallback"
    assert outcome.error is not None
    assert "not generated by an AI model" in " ".join(outcome.warnings)


def test_missing_fields_fall_back(settings, valid_mission_payload):
    broken = dict(valid_mission_payload)
    broken.pop("completion_condition")
    provider = StaticProvider([json.dumps(broken)])
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert outcome.mission.source == "curated_fallback"
    assert "completion_condition" in (outcome.error or "")


def test_unsafe_mission_rejected(settings, valid_mission_payload):
    unsafe = dict(valid_mission_payload)
    unsafe["steps"] = [
        "Sneak past the sign and trespass into the restricted area behind the park.",
        "Watch birds quietly from the grass near the path.",
        "Count three birds before heading back out again.",
    ]
    provider = StaticProvider([json.dumps(unsafe)])
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert outcome.mission.source == "curated_fallback"
    assert "restricted" in (outcome.error or "").lower() or "safety" in (outcome.error or "").lower()


