def test_provider_auth_error_short_circuits(settings, valid_mission_payload):
    class AuthFailingProvider(InferenceProvider):
        name = "auth-fail"

        def __init__(self):
            self.calls = 0

        def generate(self, prompt, *, system=None, json_mode=False):
            self.calls += 1
            raise ProviderAuthError("bad key")

    provider = AuthFailingProvider()
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert provider.calls == 1
    assert outcome.mission.source == "curated_fallback"


def test_provider_switch_does_not_change_engine_logic(settings, valid_mission_payload):
    class CustomProvider(InferenceProvider):
        name = "custom-lab"

        def generate(self, prompt, *, system=None, json_mode=False):
            return GenerationResult(
                text=json.dumps(valid_mission_payload),
                provider=self.name,
                model="custom-model-7b",
                latency_ms=5,
            )

    outcome = generate_mission(make_request(), settings, provider=CustomProvider())
    assert outcome.mission.source == "ai"
    assert outcome.mission.provider == "custom-lab"
    assert outcome.mission.model == "custom-model-7b"


def test_engine_stops_after_bounded_attempts(settings):
    provider = StaticProvider(["still not json", "also bad", "nope", "never"])
    outcome = generate_mission(make_request(), settings, provider=provider)

    assert outcome.mission.source == "curated_fallback"
    assert outcome.attempts == settings.max_generation_attempts
    assert provider.calls == settings.max_generation_attempts


def test_all_fallbacks_pass_safety_and_duration_limits():
    fallbacks = load_fallbacks()
    assert len(fallbacks) >= 6
    for mission in fallbacks:
        report = check_mission(mission)
        assert report.ok, f"{mission.title}: {report.violations}"
        assert len(mission.steps) <= MAX_STEPS_BY_DURATION[int(mission.duration_minutes)]
        assert mission.source == "curated_fallback"


def test_parse_mission_rejects_extra_steps(settings, valid_mission_payload):
    payload = dict(valid_mission_payload)
    payload["steps"] = [f"Step number {i} with enough words to pass." for i in range(7)]
    request = make_request(duration_minutes=10)
    try:
        parse_mission(json.dumps(payload), request, provider="static", model="m")
    except Exception as exc:
        assert "steps" in str(exc).lower()
    else:
        raise AssertionError("expected MissionValidationError for 10-minute mission with 7 steps")


def test_build_prompt_contains_core_constraints():
    prompt = build_prompt(make_request(duration_minutes=10, interests=["plants", "sounds"]))
    assert "10 minutes" in prompt
    assert "Plants" in prompt
    assert "JSON" in prompt
    assert "traffic" in prompt.lower()
    assert "No special equipment" in prompt


