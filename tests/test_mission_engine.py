def test_missing_api_key_returns_fallback(settings):
    from dataclasses import replace

    no_key = replace(settings, api_key=None)
    outcome = generate_mission(make_request(), no_key)

    assert outcome.mission.source == "curated_fallback"
    assert outcome.attempts == 0
    assert "OPENROUTER_API_KEY" in (outcome.error or "")


